def _v1_csqa_rows() -> set:
    """CSQA row ids already used by sb_spoken (its clip keys are 'csqa/<row id>')."""
    rows = set()
    for fn in ("items_train.jsonl", "items_cal.jsonl", "items_train_full.jsonl", "items_train_strict.jsonl"):
        fp = Path(f"{VOL}/stageb/sb_spoken/{fn}")
        if not fp.exists():
            continue
        with fp.open() as f:
            for ln in f:
                it = json.loads(ln)
                a = it.get("audio") or {}
                if str(a.get("key", "")).startswith("csqa/"):
                    rows.add(a["key"].split("/", 1)[1])
                if it.get("source") == "spoken_qa_csqa" and it.get("meta", {}).get("row_id"):
                    rows.add(it["meta"]["row_id"])
    plan = Path(f"{VOL}/stageb/sb_spoken/work/tts_plan.json")
    if plan.exists():  # every CSQA row sb_spoken planned (even if its clip was later dropped)
        for sh in json.loads(plan.read_text())["shards"]:
            for s in sh:
                if s.get("source") == "spoken_qa_csqa":
                    rows.add(s["row_id"])
    return rows


@app.function(image=cpu_image, volumes={VOL: volume}, timeout=3600, memory=16384, secrets=[hf_secret])
def prepare(smoke: bool = False) -> list[list[dict]]:
    import random
    from collections import Counter

    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download

    import build as B

    cfg = SMOKE if smoke else FULL
    OUT = out_dir(smoke)

    def pqrows(repo, rev, split):
        p = hf_hub_download(repo, f"data/{split}-00000-of-00001.parquet", repo_type="dataset", revision=rev, cache_dir="/tmp/hf")
        return pq.read_table(p).to_pylist()

    v1_rows = _v1_csqa_rows()
    cs = B.csqa_rows(pqrows(CSQA_REPO, CSQA_REV, "train"))
    s_cs, st_cs = B.dataset_specs(cs, ds="csqa", source="spoken_csqa", licence="MIT", dataset="tau/commonsense_qa",
                                  n_max=cfg["csqa"], fmt_weights=[("read", 0.40), ("stem", 0.35), ("yn", 0.25)],
                                  read_k=None, exclude=v1_rows)
    qa = B.qasc_rows(pqrows(QASC_REPO, QASC_REV, "train"), "train") + B.qasc_rows(pqrows(QASC_REPO, QASC_REV, "validation"), "validation")
    s_qa, st_qa = B.dataset_specs(qa, ds="qasc", source="spoken_qasc", licence="CC BY 4.0", dataset="allenai/qasc",
                                  n_max=cfg["qasc"], fmt_weights=[("read", 0.35), ("stem", 0.45), ("yn", 0.20)], read_k=4,
                                  group_of=lambda g: g["fact1"])
    qz = []
    for sp in ("train", "validation", "test"):
        qz += B.quartz_rows(pqrows(QUARTZ_REPO, QUARTZ_REV, sp), sp)
    s_qz, st_qz = B.dataset_specs(qz, ds="quartz", source="spoken_quartz", licence="CC BY 4.0", dataset="allenai/quartz",
                                  n_max=cfg["quartz"], fmt_weights=[("read", 0.50), ("stem", 0.50)], read_k=None,
                                  group_of=lambda g: g["para_id"])
    s_gen, st_gen = B.generated_specs(cfg["gen_scale"])
    specs = s_cs + s_qa + s_qz + s_gen
    assert len({s["clip"] for s in specs}) == len(specs), "duplicate clip keys"
    voice_wer = json.loads(Path("/root/voice_wer.json").read_text())
    train_v, cal_v = B.split_voices(B.english_voices(voice_wer))
    B.assign_voices(specs, train_v, cal_v)
    random.Random(f"{B.C.SEED}:shards2").shuffle(specs)
    n = cfg["shard"]
    shards = [specs[i : i + n] for i in range(0, len(specs), n)]
    work = Path(f"{OUT}/work")
    work.mkdir(parents=True, exist_ok=True)
    info = {"n_specs": len(specs), "n_items_planned": sum(len(s["qas"]) for s in specs),
            "v1_csqa_rows_excluded": len(v1_rows), "csqa": dict(st_cs), "qasc": dict(st_qa), "quartz": dict(st_qz),
            "generated": dict(st_gen), "voices_train": train_v, "voices_cal": cal_v,
            "by_source_variant": dict(Counter(f"{s['source']}|{s['variant']}|{'CAL' if s['cal'] else 'train'}" for s in specs)),
            "n_shards": len(shards)}
    (work / f"tts_plan_{RUN_TAG}.json").write_text(json.dumps({"info": info, "shards": shards}))
    volume.commit()
    print("PLAN", json.dumps({k: v for k, v in info.items() if k != "by_source_variant"})[:3000], flush=True)
    return shards


@app.function(image=tts_image, gpu=["L4", "A10G"], max_containers=2, volumes={VOL: volume}, timeout=3 * 3600,
              secrets=[hf_secret], retries=1)
def tts_shard(idx: int, specs: list[dict], smoke: bool = False, n_asr: int = 12) -> dict:
    import re

    import numpy as np
    from huggingface_hub import hf_hub_download
    from kokoro import KModel, KPipeline
    from scipy.signal import resample_poly

    import common as C

    t0 = time.time()
    OUT = out_dir(smoke)
    cfg = hf_hub_download(KOKORO_REPO, "config.json", revision=KOKORO_REV)
    mdl = hf_hub_download(KOKORO_REPO, "kokoro-v1_0.pth", revision=KOKORO_REV)
    model = KModel(config=cfg, model=mdl).to("cuda").eval()
    pipes = {lc: KPipeline(lang_code=lc, model=model) for lc in "ab"}
    vpath = {}
    clips, durs, skipped = {}, {}, {}
    pad = np.zeros(int(0.15 * C.SAMPLE_RATE), np.float32)
    for s in specs:
        v = s["voice"]
        if v not in vpath:
            vpath[v] = hf_hub_download(KOKORO_REPO, f"voices/{v}.pt", revision=KOKORO_REV)
        lc = "b" if v.startswith("b") else "a"
        try:
            chunks = [r.audio.cpu().numpy() for r in pipes[lc](s["tts_text"], voice=vpath[v], speed=s["speed"]) if r.audio is not None]
        except Exception as e:  # noqa: BLE001
            skipped[s["clip"]] = f"error: {e!r}"[:200]
            continue
        if not chunks:
            skipped[s["clip"]] = "no audio"
            continue
        x = resample_poly(np.concatenate(chunks).astype(np.float64), 2, 3).astype(np.float32)  # 24 kHz -> 16 kHz
        x = np.concatenate([pad, x, pad])
        pk = float(np.max(np.abs(x)))
        if pk > 0.99:
            x = x * (0.99 / pk)
        if len(x) > 20 * C.SAMPLE_RATE:
            skipped[s["clip"]] = f"too long {len(x) / C.SAMPLE_RATE:.1f}s"
            continue
        clips[s["clip"]] = x.astype(np.float32)
        durs[s["clip"]] = len(x) / C.SAMPLE_RATE
    synth_s = time.time() - t0
    bank = f"sb_spoken2_{RUN_TAG}_tts{idx:02d}"
    C.write_audio_bank(f"{OUT}/audio", bank, clips)
    asr = []
    try:  # intelligibility spot check with Whisper
        from transformers import pipeline as hf_pipeline

        rec = hf_pipeline("automatic-speech-recognition", model="openai/whisper-small.en", device=0)

        def norm(t):
            return re.sub(r"[^a-z0-9 ]", " ", t.lower()).split()

        def wer(ref, hyp):
            r, h = norm(ref), norm(hyp)
            dp = list(range(len(h) + 1))
            for i in range(1, len(r) + 1):
                prev, dp[0] = dp[0], i
                for j in range(1, len(h) + 1):
                    cur = min(dp[j] + 1, dp[j - 1] + 1, prev + (r[i - 1] != h[j - 1]))
                    prev, dp[j] = dp[j], cur
            return dp[len(h)] / max(1, len(r))

        allk = sorted(clips)
        keys = allk[:: max(1, len(allk) // max(1, n_asr))][:n_asr]
        text_of = {s["clip"]: s["text"] for s in specs}
        for k in keys:
            hyp = rec({"raw": clips[k], "sampling_rate": C.SAMPLE_RATE})["text"]
            asr.append({"clip": k, "ref": text_of[k], "hyp": hyp, "wer": round(wer(text_of[k], hyp), 3),
                        "dur": round(durs[k], 2)})
    except Exception as e:  # noqa: BLE001
        asr.append({"error": repr(e)[:300]})
    res = {"idx": idx, "bank": bank, "durations": durs, "skipped": skipped, "asr": asr,
           "synth_seconds": round(synth_s, 1), "seconds": round(time.time() - t0, 1),
           "audio_seconds": round(sum(durs.values()), 1)}
    work = Path(f"{OUT}/work")
    work.mkdir(parents=True, exist_ok=True)
    (work / f"tts_result_{RUN_TAG}_{idx:02d}.json").write_text(json.dumps(res))
    volume.commit()
    print("SHARD", idx, len(clips), "clips", res["audio_seconds"], "s audio in", res["synth_seconds"], "s; skipped",
          len(skipped), flush=True)
    return {k: v for k, v in res.items() if k != "durations"}


def _adi_text_index(adi: list[dict]):
    import build as B

    exact, sh = set(), set()
    for it in adi:
        texts = []
        if it.get("state_text"):
            texts += [it["state_text"], it["state_text"].split("\n")[0]]
        texts.append(it.get("question") or "")
        texts += [str(o) for o in it.get("options") or []]
        for t in texts:
            n = B.norm_text(t)
            if len(n.split()) >= 3:
                exact.add(n)
            sh |= B.shingles(t)
    return exact, sh


def _meta_strings(adi: list[dict]) -> set:
    out = set()
    for it in adi:
        out.add(str(it.get("item_key")))
        for k, v in (it.get("meta") or {}).items():
            if isinstance(v, (str, int)) and not isinstance(v, bool):
                out.add(str(v))
    return out


@app.function(image=cpu_image, volumes={VOL: volume}, timeout=3600, memory=32768)
def assemble(smoke: bool = False, timings: dict | None = None) -> dict:
    import random
    import statistics
    from collections import Counter, defaultdict

    import build as B
    import common as C

    volume.reload()
    t0 = time.time()
    OUT = out_dir(smoke)
    work = Path(f"{OUT}/work")
    plan = json.loads((work / f"tts_plan_{RUN_TAG}.json").read_text())
    specs = [s for sh in plan["shards"] for s in sh]
    shard_of = {s["clip"]: i for i, sh in enumerate(plan["shards"]) for s in sh}
    results = {}
    for fp in sorted(work.glob(f"tts_result_{RUN_TAG}_*.json")):
        r = json.loads(fp.read_text())
        results[r["idx"]] = r
    missing_shards = [i for i in range(len(plan["shards"])) if i not in results]

    # Evaluation set, for leakage checks
    adi_path = Path(f"{VOL}/adi/items.jsonl")
    adi = [json.loads(ln) for ln in adi_path.open()] if adi_path.exists() else []
    adi_exact, adi_sh = _adi_text_index(adi)
    adi_meta = _meta_strings(adi)
    # Eval items: text check as well
    ev_path = Path(f"{VOL}/data/eval_items.jsonl")
    ev = [json.loads(ln) for ln in ev_path.open()] if ev_path.exists() else []
    ev_exact, ev_sh = _adi_text_index(ev)

    templates = set(B.READ_Q + B.STEM_Q + B.YN_Q + B.VALID_Q + B.VALID_YN_Q + B.CONCL_Q)
    items, dropped, hits = [], Counter(), []
    sec_per_word = []
    for s in specs:
        r = results.get(shard_of[s["clip"]])
        if r is None:
            dropped["shard_missing"] += 1
            continue
        dur = r["durations"].get(s["clip"])
        if dur is None:
            dropped["tts_skipped"] += 1
            continue
        # content texts only: the typed format templates (VoiceBench / Big Bench Audio wording) are excluded on purpose
        txts = [s["stem"], s["text"]] + [qa["question"] for qa in s["qas"] if qa["question"] not in templates] + \
               [o for qa in s["qas"] for o in qa["options"] if len(str(o).split()) >= 5]
        hit = None
        for t in txts:
            n = B.norm_text(t)
            if (len(n.split()) >= 3 and n in adi_exact) or (B.shingles(t) & adi_sh):
                hit = ("adi", t)
                break
            if (len(n.split()) >= 3 and n in ev_exact) or (B.shingles(t) & ev_sh):
                hit = ("exp0_eval", t)
                break
        if hit:
            dropped[f"text_overlap_{hit[0]}"] += 1
            hits.append({"clip": s["clip"], "with": hit[0], "text": hit[1][:200]})
            continue
        sec_per_word.append(dur / max(1, B.n_words(s["text"])))
        items += B.make_items(s, r["bank"], dur)

    train = [it for it in items if it["set"] == "train"]
    cal = [it for it in items if it["set"] == "CAL"]

    bank_index = {}
    for fp in Path(f"{OUT}/audio").glob(f"sb_spoken2_{RUN_TAG}_tts*.json"):
        bank_index[fp.stem] = json.loads(fp.read_text())
    val = B.validate(items, bank_index)

    # CAL disjointness (voices, source rows / puzzle ids, CAL groups, spoken texts)
    def col(xs, key):
        return {it["meta"].get(key) for it in xs} - {None}

    tr_text = {B.norm_text(it["meta"]["transcript"]) for it in train}
    cal_text = {B.norm_text(it["meta"]["transcript"]) for it in cal}
    cal_check = {"voice_overlap": sorted(col(train, "voice") & col(cal, "voice")),
                 "row_overlap": len(col(train, "row_id") & col(cal, "row_id")),
                 "group_overlap": len(col(train, "group") & col(cal, "group")),
                 "spoken_text_overlap": len(tr_text & cal_text), "cal_share": round(len(cal) / max(1, len(items)), 4),
                 "cal_voices": sorted(col(cal, "voice")), "n_train_voices": len(col(train, "voice"))}

    # Evaluation-set id / speaker checks (our sources are not in it; voices are Kokoro voices)
    rows_used = col(items, "row_id")
    voices_used = col(items, "voice")
    adi_sources = sorted({str(it.get("source")) for it in adi})
    leakage = {
        "adi_items_file": str(adi_path), "adi_items": len(adi), "adi_sources": adi_sources,
        "source_datasets_in_adi": [d for d in ("commonsense", "qasc", "quartz") if any(d in s.lower() for s in adi_sources)],
        "row_id_overlap_with_adi_meta": sorted(rows_used & adi_meta)[:20],
        "voice_overlap_with_adi_meta": sorted(voices_used & adi_meta),
        "text_overlap_dropped": {k: v for k, v in dropped.items() if k.startswith("text_overlap")},
        "text_overlap_examples": hits[:15],
        "text_check": "normalised exact match (>= 3 words) or any shared 8-word shingle (whole text if 5-7 words) between "
                      "our spoken stem / transcript / typed question / long options and the evaluation set's state_text, "
                      "questions and options (VoiceBench text twins incl. OpenBookQA + MMLU stems, MMSU, ...) and the eval items",
        "exp0_eval_items": len(ev),
        "excluded_sources_never_used": "VoiceBench, MMSU, Big Bench Audio, BIG-bench/BBH, OpenBookQA, ARC, MMLU, GSM8K, "
                                       "MuSR, HellaSwag, WinoGrande, BoolQ, StrategyQA (BIG-bench task), SciQ (NC), PIQA, "
                                       "Social IQa, LogiQA (licence not verifiable)",
        "v1_csqa_rows_excluded": plan["info"]["v1_csqa_rows_excluded"],
    }
    tr_csqa = {it["meta"]["row_id"] for it in items if it["source"] == "spoken_csqa"}
    leakage["csqa_rows_overlap_with_v1_sb_spoken"] = len(tr_csqa & _v1_csqa_rows())

    used_clips = {(it["audio"]["bank"], it["audio"]["key"]) for it in items}
    hours_by_source = defaultdict(float)
    clip_src = {(it["audio"]["bank"], it["audio"]["key"]): it["source"] for it in items}
    for b, k in used_clips:
        hours_by_source[clip_src[(b, k)]] += bank_index[b][k][1] / C.SAMPLE_RATE / 3600
    hours = sum(hours_by_source.values())

    # Write (summary.json last)
    C.write_jsonl(f"{OUT}/items_train.jsonl", train)
    C.write_jsonl(f"{OUT}/items_cal.jsonl", cal)
    counts = defaultdict(Counter)
    fam_var = Counter()
    for it in items:
        counts[it["source"]][f"{it['set']}|{it['meta']['qtype']}"] += 1
        fam_var[f"{it['meta']['family']}|{it['meta']['variant']}"] += 1
    examples = {}
    rng = random.Random(C.SEED)
    for src in sorted(counts):
        pool = [it for it in items if it["source"] == src]
        examples[src] = [{"id": it["id"], "transcript": it["meta"]["transcript"], "question": it["question"],
                          "options": it["options"], "gold": it["gold"], "channel": it["channel"]}
                         for it in rng.sample(pool, min(3, len(pool)))]
    asr = [a for r in results.values() for a in r.get("asr", []) if "wer" in a]
    asr_err = [a for r in results.values() for a in r.get("asr", []) if "error" in a]
    tts_skipped = {k: v for r in results.values() for k, v in r.get("skipped", {}).items()}
    tts_s = sum(r.get("seconds", 0) for r in results.values())
    spw = sorted(sec_per_word)
    summary = {
        "builder": "sb_spoken2",
        "built_at": time.strftime("%Y-%m-%d %H:%M:%S %Z"),
        "smoke": smoke,
        "paths": {"items_train": f"{OUT}/items_train.jsonl", "items_cal": f"{OUT}/items_cal.jsonl",
                  "audio_dir": f"{OUT}/audio", "banks": sorted(bank_index)},
        "n_items": {"train": len(train), "CAL": len(cal), "clips": len(used_clips)},
        "counts_by_source": {k: dict(sorted(v.items())) for k, v in sorted(counts.items())},
        "counts_by_family_variant": dict(sorted(fam_var.items())),
        "channel": dict(Counter(f"{it['set']}|{it['channel']}" for it in items)),
        "audio_hours": {"total": round(hours, 3), **{k: round(v, 3) for k, v in sorted(hours_by_source.items())}},
        "sources": SOURCES,
        "examples": examples,
        "leakage": leakage,
        "cal_disjointness": cal_check,
        "validation": val,
        "tts_seconds_per_word": {"p01": round(spw[len(spw) // 100], 3) if spw else None,
                                 "median": round(statistics.median(spw), 3) if spw else None,
                                 "p99": round(spw[len(spw) * 99 // 100], 3) if spw else None,
                                 "n_below_0.2": sum(1 for v in spw if v < 0.2)},
        "build_stats": {"plan": plan["info"], "dropped": dict(dropped), "tts_skipped": len(tts_skipped),
                        "tts_skipped_examples": dict(list(tts_skipped.items())[:10]), "missing_shards": missing_shards},
        "tts_asr_check": {"n": len(asr), "mean_wer": round(sum(a["wer"] for a in asr) / max(1, len(asr)), 4),
                          "n_wer_over_0.3": sum(1 for a in asr if a["wer"] > 0.3),
                          "worst": sorted(asr, key=lambda a: -a["wer"])[:6], "errors": asr_err[:3]},
        "compute": {"tts_container_seconds": round(tts_s, 1), "timings": timings or {},
                    "est_cost_usd": round(tts_s / 3600 * 0.80 + 0.30, 2)},
        "assemble_seconds": round(time.time() - t0, 1),
    }
    (Path(OUT) / "summary.json").write_text(json.dumps(summary, indent=1))
    volume.commit()
    brief = {k: summary[k] for k in ("n_items", "counts_by_source", "audio_hours", "cal_disjointness", "validation",
                                     "tts_asr_check", "tts_seconds_per_word", "channel")}
    print("SUMMARY", json.dumps(brief, indent=1)[:8000], flush=True)
    print("LEAKAGE", json.dumps(leakage)[:3000], flush=True)
    return brief


@app.function(image=cpu_image, volumes={VOL: volume}, timeout=5 * 3600, memory=4096)
def orchestrate(smoke: bool = False) -> dict:
    t0 = time.time()
    cfg = SMOKE if smoke else FULL
    shards = prepare.remote(smoke)
    t_plan = time.time() - t0
    res = list(tts_shard.starmap([(i, sh, smoke, cfg["n_asr"]) for i, sh in enumerate(shards)], return_exceptions=True))
    errs = [repr(r)[:300] for r in res if isinstance(r, Exception)]
    if errs:
        print("TTS shard errors:", errs, flush=True)
    timings = {"plan_s": round(t_plan, 1), "tts_done_s": round(time.time() - t0, 1), "tts_shard_errors": errs}
    out = assemble.remote(smoke, timings)
    out["timings"] = timings
    out["audio_readback_check"] = check_audio.remote(smoke)
    return out


@app.function(image=cpu_image, volumes={VOL: volume}, timeout=1800, memory=16384)
def check_audio(smoke: bool = False, n: int = 300) -> dict:
    """Load a sample of written items through common.item_audio and check the waveforms (finite, length, peak, <= 20 s)."""
    import random
    from collections import Counter

    import numpy as np

    import common as C

    OUT = out_dir(smoke)
    items = C.read_jsonl(f"{OUT}/items_train.jsonl") + C.read_jsonl(f"{OUT}/items_cal.jsonl")
    sample = random.Random(C.SEED).sample(items, min(n, len(items)))
    banks = {b: C.AudioBank(f"{OUT}/audio", b) for b in sorted({it["audio"]["bank"] for it in sample})}
    probs, chans, durs, rms = Counter(), Counter(), [], []
    for it in sample:
        x = C.item_audio(it, banks)
        chans[it["channel"]] += 1
        L = banks[it["audio"]["bank"]].index[it["audio"]["key"]][1]
        if x is None or len(x) != L:
            probs["length"] += 1
            continue
        if not np.all(np.isfinite(x)):
            probs["nan"] += 1
        if it["channel"] == "clean" and float(np.max(np.abs(x))) > 0.99 + 1e-6:
            probs["peak"] += 1
        r = float(np.sqrt(np.mean(x ** 2)))
        rms.append(r)
        if r < 1e-3:
            probs["silent"] += 1
        if len(x) / C.SAMPLE_RATE > 20.0:
            probs["too_long"] += 1
        durs.append(len(x) / C.SAMPLE_RATE)
    out = {"n_checked": len(sample), "problems": dict(probs), "channels": dict(chans),
           "dur_s": {"min": round(min(durs), 2), "mean": round(sum(durs) / len(durs), 2), "max": round(max(durs), 2)},
           "rms": {"min": round(min(rms), 4), "median": round(sorted(rms)[len(rms) // 2], 4)}}
    sp = Path(f"{OUT}/summary.json")  # record the read-back check in the summary (items/banks are not touched)
    if sp.exists():
        summ = json.loads(sp.read_text())
        summ["audio_readback_check"] = out
        sp.write_text(json.dumps(summ, indent=1))
        volume.commit()
    print("CHECK", json.dumps(out), flush=True)
    return out


