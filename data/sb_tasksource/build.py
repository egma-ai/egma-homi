def _alnum(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def leaderboard_match(task_id: str, repos=()) -> str | None:
    """The first leaderboard pattern found in the task id or in a dataset name it loads, else None."""
    names = [task_id] + [r.split("/")[-1] for r in repos if r]
    for name in names:
        low, an = name.lower(), _alnum(name)
        for p in LEADERBOARD_PATTERNS:
            if p in low or _alnum(p) in an:
                return f"leaderboard overlap: '{p}' in '{name}'"
    return None


def content_overlap_match(task_id: str) -> str | None:
    return next((why for pat, why in CONTENT_OVERLAP_TASKS.items() if re.search(pat, task_id)), None)


def closed_model_match(task_id: str, repos=()) -> str | None:
    for pat, why in CLOSED_MODEL_TASKS.items():
        if re.search(pat, task_id) or any(re.search(pat, r) for r in repos if r):
            return f"closed-model outputs: {why}"
    return None


def bucket_of(task_id: str) -> str:
    return next(name for name, pat in BUCKETS.items() if re.search(pat, task_id))


def family_of(task_id: str) -> str:
    """Dataset family: first id component; multilingual -> 'multilingual/<dataset>'; each procedural generator alone."""
    parts = task_id.split("/")
    if parts[0] == "procedural-typed-decisions":
        return task_id
    if parts[0] == "multilingual":
        return "/".join(parts[:2])
    return parts[0]


# Licences (stricter than tasksource's `commercial`): every licence recorded for a task must be one of
# CC0 / public domain, CC BY, CC BY-SA (flagged), Apache-2.0, MIT, BSD, ODC-BY, ODbL.

def licence_token_class(tok: str) -> str:
    """'ok', 'share_alike' or 'bad' for one licence name (Hub card id like 'cc-by-4.0' or DPI name 'CC BY 4.0 (DPI)')."""
    t = tok.lower().replace("(dpi)", "").strip()
    t = re.sub(r"\s+", " ", t)
    if not t or t in {"unspecified", "unknown", "other", "cc", "custom", "various", "no license"}:
        return "bad"
    if re.search(r"(^|[\s-])nc($|[\s-])|non-?commercial|academic|research|(^|[\s-])nd($|[\s-])", t):
        return "bad"
    if re.match(r"^(cc0|cc-0|public domain|pddl|unlicense)", t):
        return "ok"
    if re.match(r"^cc[\s-]by[\s-]sa", t):
        return "share_alike"
    if re.match(r"^cc[\s-]by([\s-]\d(\.\d)?)?$", t):
        return "ok"
    if re.match(r"^(apache|mit\b|mit license|bsd|odc-by|odc by|odbl)", t):
        return "ok"
    return "bad"  # gpl/agpl/mpl/afl/oanc/openrail/llama/custom/... : not on our whitelist


def licence_decision(task_id: str, ts_info: dict | None, yaml_info: dict | None, row_uses: set) -> tuple[bool, str, dict]:
    """(keep, reason, record). Most restrictive wins across the tasksource package, sources.yaml and the rows."""
    rec = {"tasksource_license": ts_info.get("license") if ts_info else None,
           "tasksource_license_use": ts_info.get("license_use") if ts_info else None,
           "card_license": yaml_info.get("license") if yaml_info else None,
           "card_license_use": yaml_info.get("license_use") if yaml_info else None,
           "row_license_use": sorted(row_uses)}
    uses = {u for u in (rec["tasksource_license_use"], rec["card_license_use"]) if u} | set(row_uses)
    if ts_info is None and not task_id.startswith("procedural-typed-decisions/"):
        return False, "not in the tasksource licence catalog", rec
    if uses != {"commercial"}:
        return False, f"licence_use {sorted(uses)} (needs commercial everywhere)", rec
    toks = set()
    for s in (rec["tasksource_license"], rec["card_license"]):
        if s:
            toks |= {t.strip() for t in s.split(",") if t.strip()}
    classes = {t: licence_token_class(t) for t in sorted(toks)}
    bad = [t for t, c in classes.items() if c == "bad"]
    rec["licences"] = sorted(toks)
    rec["share_alike"] = any(c == "share_alike" for c in classes.values())
    if not toks:
        return False, "no licence recorded", rec
    if bad:
        return False, f"licence not on whitelist: {bad}", rec
    return True, "ok", rec


# Row -> item

class NoShuffle(random.Random):
    """rng whose shuffle keeps the order (score levels low -> high, options that cite other options)."""

    def shuffle(self, x, *args, **kwargs):  # noqa: D401
        return None


_POSITIONAL = re.compile(
    r"\b(above|below|previous|following)\b|"
    r"(^|\W)\(?[A-Ea-e1-5]\)?\s*(and|&|or|,)\s*\(?[A-Ea-e1-5]\)?(\W|$)|"
    r"\b(options?|answers?|choices?)\s+\(?[A-Ea-e1-5]\)?\b|"
    r"^\(?[A-Ea-e]\)?$|\bonly\s+\(?[A-E1-5]\)?\b|\b(both|neither)\s+\(?[A-E1-5]\)?\b")


def positional_refs(options) -> bool:
    """True when an option refers to other options by position/letter ('A and B', 'all of the above')."""
    return any(_POSITIONAL.search(o) for o in options if isinstance(o, str))


# noul targets are P(answer is yes). Questions not phrased as yes/no ("How likely ...?", "What is the probability ...?")
# get an explicit reading of the two options.
YES_NO_QUESTION = re.compile(r"^(is|are|am|was|were|does|do|did|can|could|should|would|will|shall|has|have|had|may|"
                             r"might|must)\b", re.I)
NOUL_HINT = "(yes = it is true, no = it is not)"


def is_hard(target) -> bool:
    return max(target) >= 0.999


def row_problem(row: dict) -> str | None:
    """Why a raw row cannot become an item (None = fine). Cheap: used on every candidate row."""
    kind, opts, tgt = row["kind"], list(row["options"] if row["options"] is not None else []), list(row["target"])
    q, state = row["question"], row["state"]
    if not isinstance(q, str) or not q.strip():
        return "empty question"
    if not isinstance(state, str):
        state = json.dumps(state, ensure_ascii=False)
    if len(state) > MAX_STATE_CHARS:
        return "state too long"
    if kind == "noul":
        if len(tgt) != 1 or not (0.0 <= tgt[0] <= 1.0) or math.isnan(tgt[0]):
            return "bad noul target"
        return None
    if kind not in ("choice", "score"):
        return f"unknown kind {kind}"
    if not 2 <= len(opts) <= MAX_OPTIONS:
        return "option count"
    if any(not isinstance(o, str) or not o.strip() for o in opts):
        return "empty option"
    if len({o.strip().lower() for o in opts}) != len(opts):
        return "duplicate options"
    if len(tgt) != len(opts) or any(t < 0 or math.isnan(t) for t in tgt) or abs(sum(tgt) - 1.0) > 1e-3:
        return "bad target"
    if len(state) + len(q) + sum(len(o) for o in opts) > MAX_TOTAL_CHARS:
        return "prompt too long"
    return None


def convert_row(row: dict, *, set_name: str, source: str, meta_extra: dict) -> dict:
    """One dataset row -> one item. Hard labels: smoothed one-hot for train, exact one-hot for CAL; soft labels
    (annotator votes, mean ratings, probabilities) are kept as soft targets."""
    kind = row["kind"]
    state = row["state"] if isinstance(row["state"], str) else json.dumps(row["state"], ensure_ascii=False)
    question = row["question"].strip()
    rng = random.Random(f"{C.SEED}:{BUILDER}:{row['id']}")
    if kind == "noul":
        if not YES_NO_QUESTION.match(question):  # e.g. "How likely is the hypothesis to be true...?"
            question = f"{question} {NOUL_HINT}"
        p = float(row["target"][0])
        options, gold = ["yes", "no"], (0 if p >= 0.5 else 1)
        hard = p in (0.0, 1.0)
        target = [p, 1.0 - p]
        keep_order = False
    else:
        options = [o.strip() for o in row["options"]]
        t = [float(x) for x in row["target"]]
        s = sum(t)
        target = [x / s for x in t]
        gold = max(range(len(target)), key=lambda i: target[i])
        hard = is_hard(target)
        keep_order = kind == "score" or positional_refs(options)
    if hard:
        target = list(C.smooth_one_hot(len(options), gold, LABEL_SMOOTHING)) if set_name == "train" else \
            [1.0 if i == gold else 0.0 for i in range(len(options))]
    meta = {"qtype": kind, "soft": not hard, "positional_order_kept": bool(keep_order and kind != "score"),
            "variant": row["variant"], "group_id": row["group_id"], "question_id": row["question_id"],
            "example_id": row.get("example_id"), "row_id": row["id"], "source_split": row["split"],
            "dataset": REPO, "config": CONFIG, "revision": REVISION, **meta_extra}
    return C.make_item(item_id=f"{BUILDER}/{row['id']}", set_name=set_name, source=source, question=question,
                       options=options, target=target, gold=gold, rng=NoShuffle() if keep_order else rng,
                       audio=None, channel="clean", state_text=state if state.strip() else None, meta=meta)


# Quotas and group-aware sampling

def waterfill(total: float, limits: dict) -> dict:
    """Equal shares of `total` across keys, none above its limit; leftovers go to the others."""
    out, keys, total = {}, {k for k, v in limits.items() if v > 0}, float(total)
    while keys and total > 1e-9:
        share = total / len(keys)
        full = {k for k in keys if limits[k] <= share}
        if not full:
            out.update({k: share for k in keys})
            break
        for k in full:
            out[k] = limits[k]
            total -= limits[k]
        keys -= full
    return {k: int(v) for k, v in out.items()}


def task_quotas(avail: dict, target: int = TRAIN_TARGET, task_cap: int = TASK_CAP, family_cap: int = FAMILY_CAP,
                multilingual_share: float = MULTILINGUAL_SHARE) -> dict:
    """Train items per task: families share `target` equally (each <= family_cap and <= its tasks' capacity),
    multilingual families together <= multilingual_share, then tasks share their family's quota equally (<= task_cap)."""
    fam_tasks = defaultdict(list)
    for t in avail:
        fam_tasks[family_of(t)].append(t)
    cap_t = {t: min(avail[t], task_cap) for t in avail}
    fam_limit = {f: min(family_cap, sum(cap_t[t] for t in ts)) for f, ts in fam_tasks.items()}
    fam_q = waterfill(target, fam_limit)
    ml = [f for f in fam_q if f.startswith("multilingual/")]
    ml_total, ml_max = sum(fam_q[f] for f in ml), multilingual_share * target
    if ml_total > ml_max:
        lim = {f: fam_q[f] for f in ml}
        fam_q.update(waterfill(ml_max, lim))
        rest = {f: fam_limit[f] for f in fam_q if f not in ml}
        fam_q.update(waterfill(target - sum(fam_q[f] for f in ml), rest))
    out = {}
    for f, q in fam_q.items():
        out.update(waterfill(q, {t: cap_t[t] for t in fam_tasks[f]}))
    return out


_PREFIX = re.compile(r"^(text_[ab]|passage [ab]|item [a-d]|[ab]|premise|hypothesis|sentence ?\d?|question|context)\s*:\s*")


def line_keys(state: str, min_len: int = 12) -> set:
    """Content keys of a state: its normalised lines (field prefixes like 'text_A:' / 'Item B:' stripped, >= min_len
    chars) plus the whole normalised state. Packed and reformatted variants keep the lines of the original example, so
    sharing a key means sharing source text."""
    keys = set()
    whole = normalise(state)
    if len(whole) >= min_len:
        keys.add(whole)
    for ln in re.split(r"\n+", state or ""):
        ln = _PREFIX.sub("", normalise(ln))
        if len(ln) >= min_len:
            keys.add(ln)
    return keys


def normalise(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "").lower()).strip()


def order_groups(rows: list[dict], seed: str) -> tuple[list[str], dict]:
    """Seeded random order of a task's groups (group_id -> its rows)."""
    groups = defaultdict(list)
    for r in rows:
        groups[r["group_id"]].append(r)
    gids = sorted(groups)
    random.Random(seed).shuffle(gids)
    return gids, groups


def choose_cal(gids: list[str], groups: dict, cal_quota: int) -> tuple[list[dict], set]:
    """CAL = whole held-out groups (taken from the front of the shuffled order); only non-packed rows, at most
    CAL_ROWS_PER_GROUP per group (direct first) so CAL stays diverse."""
    cal, cal_gids = [], set()
    for g in gids:
        if len(cal) >= cal_quota:
            break
        cand = sorted((r for r in groups[g] if r["variant"] != "packed_derived"),
                      key=lambda r: (r["variant"] != "direct", r["id"]))
        if cand:
            cal += cand[:CAL_ROWS_PER_GROUP]
            cal_gids.add(g)
    return cal, cal_gids


def fill_train(gids: list[str], groups: dict, quota: int, skip_gids: set, blocked_examples: set, blocked_keys: set,
               keys_of=None) -> tuple[list[dict], Counter]:
    """Whole groups in shuffled order until `quota` rows; a group is skipped if it is a CAL group, shares an
    example_id with CAL, or shares a content key (line) with a CAL state."""
    keys_of = keys_of or (lambda r: line_keys(r["state"]))
    train, stats = [], Counter()
    for g in gids:
        if len(train) >= quota:
            break
        if g in skip_gids:
            continue
        members = groups[g]
        if any(r.get("example_id") in blocked_examples for r in members):
            stats["skipped_group_shares_cal_example"] += 1
            continue
        if blocked_keys and any(keys_of(r) & blocked_keys for r in members):
            stats["skipped_group_shares_cal_text"] += 1
            continue
        train += members
    return train, stats


def rebalance_noul(items: list[dict], seed: str, ratio: float = 1.5, floor: int = 10,
                   per_task: bool = True) -> tuple[list[dict], int]:
    """Per task (or over all items), cap the majority answer of hard yes/no items at max(ratio x minority, floor).
    Returns (kept, dropped)."""
    rng = random.Random(seed)
    by_task = defaultdict(lambda: {"yes": [], "no": []})
    for i, it in enumerate(items):
        if it["meta"]["qtype"] == "noul" and not it["meta"]["soft"]:
            by_task[it["meta"]["task"] if per_task else "all"][it["options"][it["gold"]]].append(i)
    drop = set()
    for task in sorted(by_task):
        yes, no = by_task[task]["yes"], by_task[task]["no"]
        big, small = (yes, no) if len(yes) >= len(no) else (no, yes)
        keep_n = max(int(math.ceil(ratio * len(small))), floor)
        if len(big) > keep_n:
            idx = sorted(big)
            rng.shuffle(idx)
            drop.update(idx[keep_n:])
    return [it for i, it in enumerate(items) if i not in drop], len(drop)


def assign_sources(items: list[dict], max_sources: int = MAX_SOURCES) -> dict:
    """family -> item `source`: the biggest families keep their own name ('ts:<family>'), the rest share their
    tasksource bucket ('ts:<bucket>'), so there are at most `max_sources` distinct strings."""
    fam_n = Counter(it["meta"]["family"] for it in items)
    fam_bucket = {it["meta"]["family"]: it["meta"]["bucket"] for it in items}
    buckets = sorted(set(fam_bucket.values()))
    n_own = max(0, max_sources - len(buckets))
    own = {f for f, _ in sorted(fam_n.items(), key=lambda kv: (-kv[1], kv[0]))[:n_own]}
    def short(f):
        f = re.sub(r"^procedural-typed-decisions/", "proc_", re.sub(r"^multilingual/", "ml_", f))
        return re.sub(r"[^a-z0-9_]+", "_", f.lower()).strip("_")[:32]
    return {f: f"ts:{short(f)}" if f in own else f"ts:{fam_bucket[f]}" for f in fam_n}


def stable_hash(s: str) -> str:
    return hashlib.sha1(s.encode()).hexdigest()[:12]
