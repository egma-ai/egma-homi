def noul_view(is_synth: bool, family: str, rng: random.Random):
    """family 'is_real' or 'is_synth' -> (question, answer 'yes'/'no')."""
    if family == "is_real":
        return rng.choice(Q_IS_REAL), ("no" if is_synth else "yes")
    return rng.choice(Q_IS_SYNTH), ("yes" if is_synth else "no")


def choice_view(is_synth: bool, rng: random.Random):
    """-> (question, options canonical [real, synthetic], gold index)."""
    return rng.choice(Q_CHOICE), [rng.choice(OPT_REAL), rng.choice(OPT_SYNTH)], (1 if is_synth else 0)


def pair_view(synth_pos: int, ask: str, rng: random.Random):
    """synth_pos: 0 if the synthetic clip comes first. ask: 'synth' or 'real' -> (question, options, gold)."""
    q = rng.choice(Q_PAIR_SYNTH if ask == "synth" else Q_PAIR_REAL)
    opts = list(rng.choice(OPT_PAIR))
    gold = synth_pos if ask == "synth" else 1 - synth_pos
    return q, opts, gold


# Text for TTS twins
_BRACKET = re.compile(r"\[[^\]]*\]|<[^>]*>|\{[^}]*\}")


def tts_text(raw: str | None) -> str | None:
    """Transcript -> a sentence TTS can read (sentence case, brackets / noise tags removed, final punctuation)."""
    if not raw:
        return None
    t = _BRACKET.sub(" ", raw)
    t = re.sub(r"[_*#~^|\\]", " ", t)
    t = re.sub(r"\s+", " ", t).strip(" -")
    if len(re.sub(r"[^A-Za-z]", "", t)) < 4:
        return None
    if t.isupper() or t.islower():
        t = t.lower()
        t = re.sub(r"\bi\b", "I", t)
        t = re.sub(r"\bi'(m|ll|ve|d)\b", lambda m: "I'" + m.group(1), t)
    t = t[0].upper() + t[1:]
    if t[-1] not in ".?!":
        t += "."
    return t


# Balancing helpers
def duration_match(real: list[tuple[str, float]], synth: list[tuple[str, float]], rng: random.Random,
                   edges=None) -> tuple[list[str], list[str]]:
    """Histogram matching: per duration bin keep min(#real, #synth) of each class (random subset).
    Returns kept keys (real, synth)."""
    edges = edges or [1.0 + 0.5 * i for i in range(0, 59)]

    def b(d):
        for i in range(len(edges) - 1):
            if edges[i] <= d < edges[i + 1]:
                return i
        return len(edges)

    br, bs = {}, {}
    for k, d in real:
        br.setdefault(b(d), []).append(k)
    for k, d in synth:
        bs.setdefault(b(d), []).append(k)
    kr, ks = [], []
    for i in sorted(set(br) | set(bs)):
        a, c = br.get(i, []), bs.get(i, [])
        n = min(len(a), len(c))
        kr += rng.sample(a, n)
        ks += rng.sample(c, n)
    return kr, ks


def check_mmsu_nonequality(questions, mmsu_truth_path) -> dict:
    """Read only the 'question' field of each MMSU truth row; assert no item question equals one (case/space-folded)."""
    def fold(s):
        return re.sub(r"\s+", " ", str(s)).strip().lower()

    mm = set()
    with open(mmsu_truth_path) as f:
        for line in f:
            if line.strip():
                q = json.loads(line).get("question")
                if q:
                    mm.add(fold(q))
    ours = {fold(q) for q in questions}
    hits = sorted(ours & mm)
    assert not hits, f"item questions equal to MMSU questions: {hits[:5]}"
    return {"mmsu_questions": len(mm), "our_distinct_questions": len(ours), "equal": 0}


def noul_balance(items) -> dict:
    out = {}
    for it in items:
        m = it["meta"]
        if m.get("qtype") != "noul":
            continue
        k = (it["set"], m["qname"])
        a = it["options"][it["gold"]]
        out.setdefault(k, {"yes": 0, "no": 0})[a] += 1
    return {f"{s}|{q}": v for (s, q), v in sorted(out.items())}
